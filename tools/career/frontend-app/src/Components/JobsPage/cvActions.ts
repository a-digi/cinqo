import type { CvDocument, CvTemplate, Job } from '../../api'
import { personaNames } from '../CvBuilder/cvPersonaRules'

// Pure rules for the Jobs page's CV choices (step 98), kept apart from React so
// they can be checked with a script: which labels the row's CV menu shows, when
// the manual/existing/remove items are usable, the confirmation texts, and how
// the "Select existing" list is filtered. See
// plan/ai/tools/career/step-98-manual-and-existing-cv-for-a-job.md.

type CvState = Pick<Job, 'cvStatus' | 'cvMediaFileId'>

export const CV_BUILDER_PATH = '/tools/career/cv-builder'

// A job has a CV to download when an attempt completed and its file is known.
export function hasAttachedCv(job: CvState): boolean {
  return job.cvStatus === 'completed' && !!job.cvMediaFileId
}

// The manual, existing and remove items are blocked only while an AI generation
// owns the job's CV slot; the server refuses them then too (409).
export function cvChangeDisabledReason(job: Pick<Job, 'cvStatus'>): string | undefined {
  return job.cvStatus === 'generating' ? 'AI is generating a CV for this job' : undefined
}

export interface CvChoiceLabels {
  ai: string
  manual: string
  existing: string
}

// With a CV attached the three choices read as replacements.
export function choiceLabels(job: CvState): CvChoiceLabels {
  if (hasAttachedCv(job)) {
    return { ai: 'Re-generate with AI', manual: 'Create a new one manually', existing: 'Use another existing CV' }
  }
  return {
    ai: job.cvStatus === 'failed' ? 'Retry CV generation' : 'Generate CV PDF',
    manual: 'Generate manually',
    existing: 'Select existing',
  }
}

export function showRemove(job: CvState): boolean {
  return hasAttachedCv(job)
}

export interface Confirmation {
  title: string
  message: string
  confirmLabel: string
}

// Asked before replacing an attached CV; null when there is nothing to replace.
export function replaceConfirmation(job: CvState, kind: 'manual' | 'existing'): Confirmation | null {
  if (!hasAttachedCv(job)) return null
  return kind === 'manual'
    ? {
        title: 'Replace the current CV?',
        message: 'This job already has a CV. Create a new one now? It replaces the current CV for this job once it is created.',
        confirmLabel: 'Continue',
      }
    : {
        title: 'Replace the current CV?',
        message: 'Replace the current CV for this job with the one you selected?',
        confirmLabel: 'Replace',
      }
}

export const REMOVE_CONFIRMATION: Confirmation = {
  title: 'Remove CV from this job',
  message: 'Remove the CV from this job? The CV itself stays in your CV list; only the link to this job is removed.',
  confirmLabel: 'Remove',
}

export function sourceNote(source: Job['cvSource']): string {
  if (source === 'manual') return 'Created manually for this job'
  if (source === 'existing') return 'Selected from your CVs'
  if (source === 'ai') return 'Generated by the AI'
  return ''
}

// Only a document with a rendered PDF can be attached.
export function selectableDocuments(documents: CvDocument[]): CvDocument[] {
  return documents.filter((d) => d.mediaFileId !== '')
}

// Case-insensitive match on the title or any of the CV's persona names; blank shows all.
export function filterDocuments(documents: CvDocument[], query: string): CvDocument[] {
  const q = query.trim().toLowerCase()
  if (q === '') return documents
  return documents.filter((d) => d.title.toLowerCase().includes(q) || personaNames(d).toLowerCase().includes(q))
}

// "Backend, Data Lead · Classic · 30 Oct 2026"
export function documentSubtitle(doc: CvDocument, templates: Pick<CvTemplate, 'id' | 'name'>[]): string {
  const template = templates.find((t) => t.id === doc.templateId)?.name ?? doc.templateId
  const created = new Date(doc.createdAt.replace(' ', 'T') + (doc.createdAt.includes('T') ? '' : 'Z'))
  const date = Number.isNaN(created.getTime())
    ? doc.createdAt
    : created.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })
  return [personaNames(doc), template, date].filter((part) => part).join(' · ')
}

export function builderPathForJob(jobId: string): string {
  return `${CV_BUILDER_PATH}?jobId=${encodeURIComponent(jobId)}`
}
