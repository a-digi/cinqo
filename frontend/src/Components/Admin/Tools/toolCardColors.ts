// A small, stable string hash (djb2) — deterministic across reloads
// and independent of array/object iteration order, unlike relying on
// object identity or a random pick.
function hashString(value: string): number {
  let hash = 5381
  for (let i = 0; i < value.length; i++) {
    hash = (hash * 33) ^ value.charCodeAt(i)
  }
  return hash >>> 0
}

export function colorForTool(toolId: string): ToolCardColor {
  const index = hashString(toolId) % TOOL_CARD_COLORS.length
  return TOOL_CARD_COLORS[index]
}
